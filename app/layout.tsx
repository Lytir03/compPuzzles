import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { Navbar } from "@/components/Navbar";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "CompPuzzles — Ranked Puzzle Battles",
  description: "Race real players in Sudoku, Crosswords, and Nonograms. Win matches and climb the ranks.",
};

/**
 * Puzzle boards are dense grids on a phone, so the viewport must fill the
 * screen edge-to-edge — but pinch-zoom stays enabled (no `maximum-scale`),
 * since disabling it is an accessibility failure for anyone who needs to
 * magnify a 5mm crossword cell.
 */
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
};

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="flex min-h-full flex-col">
        <Navbar />
        {children}
      </body>
    </html>
  );
}
